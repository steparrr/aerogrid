// ─── helper: runway estimate from MTOW (m) ────────────────────────────────────
function rwy(mtow: number): number {
  if (mtow < 25) return 1100;
  if (mtow < 50) return 1500;
  if (mtow < 80) return 1900;
  if (mtow < 150) return 2300;
  if (mtow < 280) return 2600;
  return 3000;
}

// ─── helper: maintenance estimate $/h from MTOW & engines ────────────────────
function maint(mtow: number, eng: number): number {
  return Math.round((mtow * 8 + eng * 200) * 0.9);
}

// ─── helper: crew cost $/h from pilots count ─────────────────────────────────
function crew(pilots: number): number {
  return pilots === 26 ? 1700 : 750;
}

// ─── helper: turnaround minutes from pax ─────────────────────────────────────
function trt(pax: number): number {
  if (pax === 0) return 90;
  if (pax < 80) return 30;
  if (pax < 150) return 40;
  if (pax < 250) return 50;
  if (pax < 400) return 75;
  return 110;
}

